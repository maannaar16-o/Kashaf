class ContentPack:
    """حزمة المحتوى. النصوص المعتمدة مضمّنة؛ والخارجية تُحمَّل أو يفشل الطلب."""

    def __init__(self, external=None):
        self.external = dict(external or {})

    def external_text(self, key):
        if key not in REQUIRED_EXTERNAL:
            raise KeyError(f"مفتاح غير معرَّف: {key}")
        if key not in self.external:
            raise MissingContentError(
                f"النص «{key}» غير محمَّل. مصدره الملزم: {REQUIRED_EXTERNAL[key]}. "
                "المحرك يجمّع ولا يؤلّف — لا بديل."
            )
        return self.external[key]

    def missing(self):
        return [k for k in REQUIRED_EXTERNAL if k not in self.external]
